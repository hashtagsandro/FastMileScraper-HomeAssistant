def earfcn_to_band(earfcn: int) -> int | None:
    """Return the LTE band of a downlink EARFCN, or None if unknown."""
    for band, (_, _, n_low, n_high) in EARFCN_BAND_TABLE.items():
        if n_low <= earfcn <= n_high:
            return band
    return None


def earfcn_to_frequency(earfcn: int) -> float | None:
    """Return the downlink centre frequency in MHz, or None if unknown."""
    for f_dl_low, n_offs, n_low, n_high in EARFCN_BAND_TABLE.values():
        if n_low <= earfcn <= n_high:
            return round(f_dl_low + 0.1 * (earfcn - n_offs), 1)
    return None
